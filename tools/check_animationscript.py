#!/usr/bin/env python3
"""Checks lua/animationscript.lua against the compiled chunk in the Mac build.

The source is compiled with the patched stock Lua 5.0.2 luac and disassembled with workbench/re/lua50_chunks.py, whose
opcode table is the Mac build's (stock numbering shifted up by 4 from POW on). The stock numbers are mapped back, and the
listing must equal re/mac/lua/animationscript.lst line for line (instructions, operands, line numbers, constants,
locals and upvalues; only the header and the source name differ). This is how prelude.lua was checked too
(docs/re/embedded-lua.md section 3).
"""
import argparse, importlib.util, os, subprocess, sys

ap = argparse.ArgumentParser()
ap.add_argument("--luac", required=True)
ap.add_argument("--source", required=True)
ap.add_argument("--listing", required=True)
ap.add_argument("--disassembler", required=True)
ap.add_argument("--workdir", required=True)
a = ap.parse_args()
for needed in (a.listing, a.disassembler):
    if not os.path.isfile(needed):
        # The listing and the disassembler live in the analysis workbench; the CTest knows 77 as "skipped".
        print("skip: " + needed + " is not present (the RE listing and disassembler are workbench material)")
        sys.exit(77)
os.makedirs(a.workdir, exist_ok=True)
out = os.path.join(a.workdir, "animationscript.luac")
r = subprocess.run([a.luac, "-o", out, a.source], capture_output=True, text=True)
if r.returncode != 0:
    sys.exit("FAIL: luac: " + r.stderr)

spec = importlib.util.spec_from_file_location("lua50_chunks", a.disassembler)
mod = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mod)
stock = {n: mod.OPS[n] for n in range(16)}
for n in range(16, 35):
    stock[n] = mod.OPS[n + 4]
mod.OPS.clear()
mod.OPS.update(stock)
data = open(out, "rb").read()
_, main, _ = mod.parse_chunk(data, 0)
lines, problems = [], []
mod.disasm_func(main, lines, "main", problems)
if problems:
    sys.exit("FAIL: " + "; ".join(problems))
mine = [l for l in "\n".join(lines).split("\n")][1:]
import os
if not os.path.exists(a.listing):
    print(f"SKIP: listing {a.listing} not present (re/ is generated by workbench/re/decompile.sh and lua50_chunks.py)")
    raise SystemExit(77)
theirs = [l for l in open(a.listing).read().split("\n") if not l.startswith("; ")][1:]
mine = [l.rstrip() for l in mine]
theirs = [l.rstrip() for l in theirs]
while mine and not mine[-1]:
    mine.pop()
while theirs and not theirs[-1]:
    theirs.pop()
if mine != theirs:
    for i, (x, y) in enumerate(zip(mine, theirs)):
        if x != y:
            sys.exit("FAIL: line %d differs\n  mine:   %s\n  theirs: %s" % (i + 1, x, y))
    sys.exit("FAIL: the listings differ in length (%d vs %d lines)" % (len(mine), len(theirs)))
print("ok: animationscript.lua compiles to the same bytecode as the Mac chunk (%d listing lines)" % len(mine))
