#!/usr/bin/env python3
"""Generates src/games/choc3/audio/generated/AudioEvents.inc (docs/design/audio.md decision 6).

Inputs: docs/re/audio-events.tsv (the RE facts) and the two tables the engine owns, src/games/choc3/audio/music.tsv
(arrangement roles) and src/games/choc3/audio/music-aliases.tsv (event -> arrangement, part).

    python3 -I tools/gen_audio_events.py            write AudioEvents.inc
    python3 -I tools/gen_audio_events.py --check    exit 1 if the committed AudioEvents.inc is out of date

The inputs are cross-checked and any inconsistency is an error (exit 2): every music.tsv file belongs to its
arrangement's tsv `files`, every alias targets an arrangement, every clip in audio-music-clips.tsv has a row in
music-aliases.tsv with the same arrangement channel and fades, every Stop_<x> names an event. The old `alias_inferred`
and `unknown` rows of audio-events.tsv are superseded by the clip names (docs/re/audio.md s.10.2): a row whose name is a
clip is replaced by its alias row, and an `alias_inferred` row that is not a clip is not an event (CADI matches names
exactly, so it is silent).
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ENGINE = ROOT
AUDIO_SRC = os.path.join(ENGINE, "src", "games", "choc3", "audio")
OUT = os.path.join(AUDIO_SRC, "generated", "AudioEvents.inc")
EVENTS_TSV = os.path.join(ROOT, "docs", "re", "audio-events.tsv")
MUSIC_TSV = os.path.join(AUDIO_SRC, "music.tsv")
ALIAS_TSV = os.path.join(AUDIO_SRC, "music-aliases.tsv")
CLIPS_TSV = os.path.join(ROOT, "docs", "re", "audio-music-clips.tsv")
PORT_MUSIC_TSV = os.path.join(ROOT, "docs", "re", "audio-port-music.tsv")

KINDS = {
    "oneshot": "Oneshot", "oneshot_layered": "OneshotRandom", "loop": "Loop", "ambience_loop": "AmbienceLoop",
    "music": "Music", "stop": "Stop", "volume": "Volume", "builtin": "Builtin", "direct_file": "Direct",
    "button_sound_path": "Silent", "button_rollover_path": "Silent", "unreferenced": "Silent", "unknown": "Unknown",
}
# Known-silent by design decision 7, whatever the tsv calls them.
FORCE_SILENT = {"Stop_conveyor_belt_loop"}
# Only these `direct_file` rows reach TSound in the original. The typing names went to CADI and matched nothing (AU s.1).
def direct_plays(name):
    return name == "ui_click" or name.startswith("firework")
GROUPS = {"Sfx": "Sfx", "Environments": "Env", "Music": "Music"}
PARTS = {"start": "Start", "intro": "Intro", "outro": "Outro"}


class Bad(Exception):
    pass


def read_tsv(path):
    with open(path, encoding="utf-8") as f:
        lines = f.read().split("\n")
    header = lines[0].split("\t")
    rows = []
    for n, line in enumerate(lines[1:], 2):
        if not line.strip():
            continue
        c = line.split("\t")
        if len(c) > len(header):
            raise Bad("%s:%d has %d columns, expected %d" % (os.path.basename(path), n, len(c), len(header)))
        c += [""] * (len(header) - len(c))
        rows.append(dict(zip(header, c)))
    return rows


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def num(text, default):
    return default if text == "" else float(text)


def resources(e, names, section):
    """Per file 'primary|fallback' (AU s.10.9). files and intermittent_files share one resource_path / reforged_file
    list; `section` is where `names` start in it."""
    if not names:
        return ""
    paths = e["resource_path"].split(";") if e["resource_path"] else []
    refs = e["reforged_file"].split(";") if e["reforged_file"] else []
    total = len(e["files"].split(";")) if e["files"] else 0
    total += len(e["intermittent_files"].split(";")) if e["intermittent_files"] else 0
    if len(paths) != total or len(refs) != total:
        raise Bad("event %r: resource_path/reforged_file have %d/%d entries for %d files" % (e["event"], len(paths), len(refs), total))
    out = []
    for i, base in enumerate(names):
        path, ref = paths[section + i], refs[section + i]
        slashed = path.replace("\\", "/")
        if os.path.basename(slashed).replace(".wav", ".ogg") != base:
            raise Bad("event %r: file %r does not match resource_path %r" % (e["event"], base, path))
        qualified = "cadi/cad/" + slashed
        if ref != "-":
            out.append("cadi/audio/%s|%s" % (ref, qualified))  # Reforged ships the exact file; the CAD source is the vanilla fallback
        else:
            out.append("%s|cadi/audio/%s" % (qualified, base))
    return ";".join(out)


def generate():
    events = read_tsv(EVENTS_TSV)
    music = read_tsv(MUSIC_TSV)
    aliases = read_tsv(ALIAS_TSV)
    by_name = {}
    for e in events:
        if e["event"] in by_name:
            raise Bad("duplicate event %r in audio-events.tsv" % e["event"])
        by_name[e["event"]] = e

    out = ["// Generated by tools/gen_audio_events.py from docs/re/audio-events.tsv, games/choc3/audio/music.tsv and",
           "// games/choc3/audio/music-aliases.tsv. Do not edit.",
           "// EVENT(name, kind, group, channelVolume, files, sweeteners, intervalMinMs, intervalMaxMs, attackMs, releaseMs,",
           "//       volVary, fadeMs, srcFadeMs, stopTarget, fileRes, sweetenerRes): -1 = none. Files are ';'-separated.",
           "//       stopTarget is an event name, or @Music / @Environments for the group-wide stops. fileRes / sweetenerRes",
           "//       hold one 'primary|fallback' resource path per file (AU s.10.9): the loader tries primary, then fallback.",
           "// MUSIC(arrangement, status, sting, layers, intro, body, ending, under, tail, loop, lengthFrames, handoverFrames):",
           "//       roles and clip timing from music.tsv (AU s.10.5), ';'-separated layers.",
           "// CLIP(arrangement, file, startFrame, lengthFrames, gain): one stem clip of a port_music cue (docs/re/audio-port-music.tsv):",
           "//       the stem plays from its sample 0 for lengthFrames, gain = track volume x clip volume.",
           "// ALIAS(event, arrangement, part, masterFadeMs, sourceFadeMs): an exact clip name (AU s.10.2); -1 = none stated."]

    alias_names = {a["event"] for a in aliases}
    for e in events:
        kind = e["kind"]
        if kind == "alias_inferred" or (kind == "unknown" and e["event"] in alias_names):
            continue
        if kind not in KINDS:
            raise Bad("event %r has unknown kind %r" % (e["event"], kind))
        name = e["event"]
        k = "Silent" if name in FORCE_SILENT or (kind == "direct_file" and not direct_plays(name)) else KINDS[kind]
        group = GROUPS.get(e["group"], "Direct" if e["group"][:1].isdigit() or e["group"].startswith("0") else "Sfx")
        files = e["files"] if kind != "stop" and k != "Silent" else ""
        sweet = e["intermittent_files"] if k != "Silent" else ""
        imin = imax = -1
        if e["interval_ms"]:
            m = re.fullmatch(r"(\d+)-(\d+)", e["interval_ms"])
            if not m:
                raise Bad("event %r: bad interval_ms %r" % (name, e["interval_ms"]))
            imin, imax = int(m.group(1)), int(m.group(2))
            if imax < imin or imax == 0:
                raise Bad("event %r: interval_ms %r would spin the sweetener scheduler" % (name, e["interval_ms"]))
        attack = release = -1
        if e["envelope_ms"]:
            m = re.fullmatch(r"a(\d+)/r(\d+)", e["envelope_ms"])
            if not m:
                raise Bad("event %r: bad envelope_ms %r" % (name, e["envelope_ms"]))
            attack, release = int(m.group(1)), int(m.group(2))
        fade = srcfade = -1
        m = re.search(r"\bfade(\d+)\b", e["notes"])
        if m:
            fade = int(m.group(1))
        m = re.search(r"\bsrcfade(\d+)\b", e["notes"])
        if m:
            srcfade = int(m.group(1))
        stop = ""
        if kind == "stop" and name not in FORCE_SILENT:
            if name == "Stop_Music":
                stop = "@Music"
            elif name == "Stop_Environments":
                stop = "@Environments"
            else:
                stop = name[len("Stop_"):]
                if stop not in by_name:
                    raise Bad("%s targets %r, which is not an event" % (name, stop))
        nfiles = len(e["files"].split(";")) if e["files"] else 0
        fres = sres = ""
        if k not in ("Silent", "Direct") and kind != "stop":
            fres = resources(e, files.split(";") if files else [], 0)
            sres = resources(e, sweet.split(";") if sweet else [], nfiles)
        out.append("EVENT(%s, Kind::%s, Group::%s, %sf, %s, %s, %d, %d, %d, %d, %sf, %d, %d, %s, %s, %s)" % (
            cstr(name), k, group, repr(num(e["channel_volume"], 1.0)), cstr(files), cstr(sweet),
            imin, imax, attack, release, repr(num(e["volvary"], 0.0)), fade, srcfade, cstr(stop), cstr(fres), cstr(sres)))

    arrangements = {}
    for m in music:
        a = m["arrangement"]
        ev = by_name.get(a)
        if ev is None or ev["kind"] != "music":
            raise Bad("music.tsv: %r is not a music event in audio-events.tsv" % a)
        if a in arrangements:
            raise Bad("music.tsv: duplicate arrangement %r" % a)
        arrangements[a] = m
        tsv_files = set(ev["files"].split(";"))
        used = [f for col in ("sting", "layers", "intro", "body", "ending", "under", "tail") for f in m[col].split(";") if f]
        for f in used:
            if f not in tsv_files:
                raise Bad("music.tsv: %s: %s is not in the arrangement's files" % (a, f))
        if m["status"] not in ("settled", "inferred"):
            raise Bad("music.tsv: %s: status %r" % (a, m["status"]))
        if m["loop"] not in ("true", "false") or not m["length"].isdigit() or not m["handover"].isdigit():
            raise Bad("music.tsv: %s: bad loop/length/handover" % a)
        if int(m["handover"]) and not (m["sting"] and m["layers"]):
            raise Bad("music.tsv: %s: a hand-over offset needs a sting and layers" % a)
        out.append("MUSIC(%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)" % (
            cstr(a), cstr(m["status"]), cstr(m["sting"]), cstr(m["layers"]), cstr(m["intro"]), cstr(m["body"]),
            cstr(m["ending"]), cstr(m["under"]), cstr(m["tail"]), m["loop"], m["length"], m["handover"]))
    # The port_music cues (AU s.10.4, audio-port-music.md): per-stem clips on the cue's timeline.
    cue_arr = {a["event"]: a["arrangement"] for a in aliases if a["event"].startswith("port_music")}
    clip_rows = read_tsv(PORT_MUSIC_TSV)
    for r in clip_rows:
        arr = cue_arr.get(r["cue"])
        if arr is None or arr not in arrangements:
            raise Bad("audio-port-music.tsv: cue %r has no alias/arrangement" % r["cue"])
        m = arrangements[arr]
        if r["reforged_file"] not in m["layers"].split(";"):
            raise Bad("audio-port-music.tsv: %s is not a stem of %s" % (r["reforged_file"], arr))
        if r["cue_length_samples"] != m["length"] or m["loop"] != "true" or not r["cue_loop"].startswith("yes (loop start 0)"):
            raise Bad("audio-port-music.tsv: %s length/loop differ from music.tsv" % r["cue"])
        if r["clip_resource_start"] != "0" or r["clip_loop_start"] != "0":
            raise Bad("audio-port-music.tsv: %s %s: a clip does not start at resource sample 0" % (r["cue"], r["track_name"]))
        start, end, loop_end = int(r["clip_start_samples"]), int(r["clip_end_samples"]), int(r["clip_loop_end"])
        if end <= start or end > int(r["cue_length_samples"]):
            raise Bad("audio-port-music.tsv: bad clip span %s %s" % (r["cue"], r["track_name"]))
        # A clip longer than its resource loop region plays the region, then silence to the clip end (a recorded decision).
        length = min(end - start, loop_end)
        gain = float(r["track_volume"] or 1) * float(r["clip_volume"] or 1)
        out.append("CLIP(%s, %s, %d, %d, %sf)" % (cstr(arr), cstr(r["reforged_file"]), start, length, repr(round(gain, 7))))
    # Clips of one stem share one stream, so they must never overlap in time (windows as played, i.e. after the loop cut).
    by_stem = {}
    for r in clip_rows:
        length = min(int(r["clip_end_samples"]) - int(r["clip_start_samples"]), int(r["clip_loop_end"]))
        by_stem.setdefault((r["cue"], r["reforged_file"]), []).append((int(r["clip_start_samples"]), length))
    for key, spans in by_stem.items():
        spans.sort()
        for (s0, l0), (s1, _) in zip(spans, spans[1:]):
            if s1 < s0 + l0:
                raise Bad("audio-port-music.tsv: clips of %s %s overlap (%d + %d > %d)" % (key[0], key[1], s0, l0, s1))
    for e in events:
        if e["kind"] == "music" and e["event"] not in arrangements:
            raise Bad("music event %r has no row in music.tsv" % e["event"])

    seen = set()
    for a in aliases:
        ev = a["event"]
        if ev in seen or ev in by_name and by_name[ev]["kind"] not in ("alias_inferred", "unknown"):
            raise Bad("music-aliases.tsv: %r is duplicated or shadows an event" % ev)
        seen.add(ev)
        if a["arrangement"] not in arrangements:
            raise Bad("music-aliases.tsv: %r -> %r is not an arrangement" % (ev, a["arrangement"]))
        if a["part"] not in PARTS:
            raise Bad("music-aliases.tsv: %r has part %r" % (ev, a["part"]))
        out.append("ALIAS(%s, %s, Part::%s, %s, %s)" % (cstr(ev), cstr(a["arrangement"]), PARTS[a["part"]],
                                                       int(a["master_fade_ms"] or -1), int(a["source_fade_ms"] or -1)))
    clips = read_tsv(CLIPS_TSV)
    clip_names = {c["event"] for c in clips}
    for a in aliases:
        if a["event"] not in clip_names:
            raise Bad("music-aliases.tsv: %r is not a clip in audio-music-clips.tsv" % a["event"])
    for c in clips:
        row = next((a for a in aliases if a["event"] == c["event"]), None)
        if row is None:
            raise Bad("clip %r (audio-music-clips.tsv) has no row in music-aliases.tsv" % c["event"])
        if row["arrangement"] != c["arrangement_channel"]:
            raise Bad("%r: clips tsv says %s, music-aliases.tsv says %s" % (c["event"], c["arrangement_channel"], row["arrangement"]))
        if (row["master_fade_ms"], row["source_fade_ms"]) != (c["master_fade_ms"], c["source_fade_ms"]):
            raise Bad("%r: fades differ between the clips tsv and music-aliases.tsv" % c["event"])
        if row["part"] == "start":  # the arrangement's own timing is the start clip's (AU s.10.5)
            m = arrangements[row["arrangement"]]
            if (m["loop"], m["length"]) != (c["timeline_loop"], c["clip_end_samples"]):
                raise Bad("%r: music.tsv loop/length %s/%s differ from the clips tsv %s/%s" % (
                    c["event"], m["loop"], m["length"], c["timeline_loop"], c["clip_end_samples"]))
    return "\n".join(out) + "\n"


def main():
    try:
        text = generate()
    except Bad as err:
        print("gen_audio_events: %s" % err, file=sys.stderr)
        return 2
    if "--check" in sys.argv:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != text:
            print("AudioEvents.inc is out of date: run python3 -I tools/gen_audio_events.py", file=sys.stderr)
            return 1
        print("AudioEvents.inc is up to date")
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return 0


sys.exit(main())
